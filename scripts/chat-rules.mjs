import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, collection, getDoc, getDocs, query, where, orderBy, limit, writeBatch, updateDoc, setDoc, deleteDoc, serverTimestamp, increment } from 'firebase/firestore';

const env = await initializeTestEnvironment({ projectId: 'demo-lux-co-south', firestore: { host: '127.0.0.1', port: 8080, rules: readFileSync('firestore.rules', 'utf8') } });
const as = (uid, provider) => env.authenticatedContext(uid, { firebase: { sign_in_provider: provider } }).firestore();
const guest = as('guest-one', 'anonymous');
const other = as('guest-two', 'anonymous');
const admin = as('admin-one', 'password');
const owner = as('owner-one', 'password');
const staff = as('staff-one', 'password');
const outsider = as('outsider', 'password');
const anon = env.unauthenticatedContext().firestore();
const ref = db => doc(db, 'luxConversations', 'guest-one');
const message = db => doc(collection(ref(db), 'messages'));

try {
  await env.clearFirestore();
  await env.withSecurityRulesDisabled(async context => {
    await setDoc(doc(context.firestore(), 'luxStaff', 'admin-one'), { role: 'admin', active: true });
    await setDoc(doc(context.firestore(), 'luxStaff', 'owner-one'), { role: 'owner', active: true });
    await setDoc(doc(context.firestore(), 'luxStaff', 'staff-one'), { role: 'staff', active: true });
  });
  const first = message(guest), initial = writeBatch(guest);
  initial.set(first, { senderUid: 'guest-one', senderRole: 'customer', text: 'Is it available?', product: { id: 'AP-W001', name: 'Royal Oak', brand: 'Audemars Piguet', image: '/images/AP-W001-test.jpg', price: 5950, stock: 10, size: '42mm', movement: 'Automatic', category: '', dialColor: 'White', description: 'A watch.' }, createdAt: serverTimestamp() });
  initial.set(ref(guest), { customerUid: 'guest-one', createdAt: serverTimestamp(), updatedAt: serverTimestamp(), customerDeliveredAt: serverTimestamp(), customerSeenAt: serverTimestamp(), adminDeliveredAt: null, adminSeenAt: null, adminUnreadCount: 1, customerUnreadCount: 0, status: 'new', assignedStaffUid: null, lastMessageId: first.id, lastMessage: 'Is it available?', lastMessageAt: serverTimestamp(), lastSenderRole: 'customer' });
  await assertSucceeds(initial.commit());
  assert.equal((await assertSucceeds(getDoc(ref(guest)))).data().adminUnreadCount, 1);
  await assertFails(getDoc(ref(other)));
  await assertFails(getDoc(ref(anon)));
  await assertFails(getDocs(collection(other, 'luxConversations')));
  await assertFails(getDocs(query(collection(outsider, 'luxConversations'), orderBy('lastMessageAt', 'desc'), limit(30))));
  await assertSucceeds(getDocs(query(collection(admin, 'luxConversations'), orderBy('lastMessageAt', 'desc'), limit(30))));
  await assertFails(getDoc(ref(staff)));
  await assertSucceeds(getDocs(query(collection(staff, 'luxConversations'), where('assignedStaffUid', '==', 'staff-one'), orderBy('lastMessageAt', 'desc'), limit(30))));
  await assertSucceeds(updateDoc(ref(admin), { assignedStaffUid: 'staff-one' }));
  await assertSucceeds(getDoc(ref(staff)));
  await assertSucceeds(getDocs(query(collection(staff, 'luxConversations'), where('assignedStaffUid', '==', 'staff-one'), orderBy('lastMessageAt', 'desc'), limit(30))));
  await assertSucceeds(updateDoc(ref(staff), { status: 'open' }));
  await assertFails(updateDoc(ref(staff), { assignedStaffUid: null }));
  await assertFails(updateDoc(ref(guest), { adminUnreadCount: 0 }));
  await assertFails(updateDoc(first, { text: 'Changed' }));
  await assertFails(setDoc(doc(other, 'luxStaff', 'guest-two'), { role: 'admin', active: true }));
  const tooFast = message(guest), next = writeBatch(guest);
  next.set(tooFast, { senderUid: 'guest-one', senderRole: 'customer', text: 'Spam', product: null, createdAt: serverTimestamp() });
  next.update(ref(guest), { lastMessageId: tooFast.id, lastMessage: 'Spam', lastMessageAt: serverTimestamp(), lastSenderRole: 'customer', updatedAt: serverTimestamp(), adminUnreadCount: increment(1) });
  await assertFails(next.commit());
  await assertSucceeds(updateDoc(ref(admin), { adminDeliveredAt: serverTimestamp() }));
  await assertSucceeds(updateDoc(ref(admin), { adminDeliveredAt: serverTimestamp(), adminSeenAt: serverTimestamp(), adminUnreadCount: 0 }));
  const reply = message(admin), response = writeBatch(admin);
  response.set(reply, { senderUid: 'admin-one', senderRole: 'admin', text: 'Yes, it is available.', product: null, createdAt: serverTimestamp() });
  response.update(ref(admin), { lastMessageId: reply.id, lastMessage: 'Yes, it is available.', lastMessageAt: serverTimestamp(), lastSenderRole: 'admin', updatedAt: serverTimestamp(), customerUnreadCount: increment(1) });
  await assertSucceeds(response.commit());
  assert.equal((await getDoc(ref(guest))).data().customerUnreadCount, 1);
  await assertFails(updateDoc(ref(other), { customerSeenAt: serverTimestamp(), customerUnreadCount: 0 }));
  await assertSucceeds(updateDoc(ref(guest), { customerDeliveredAt: serverTimestamp() }));
  await assertSucceeds(updateDoc(ref(guest), { customerDeliveredAt: serverTimestamp(), customerSeenAt: serverTimestamp(), customerUnreadCount: 0 }));
  assert.equal((await getDoc(ref(guest))).data().customerUnreadCount, 0);
  const answer = message(guest), answerBatch = writeBatch(guest);
  answerBatch.set(answer, { senderUid: 'guest-one', senderRole: 'customer', text: 'Great, thank you.', product: null, createdAt: serverTimestamp() });
  answerBatch.update(ref(guest), { lastMessageId: answer.id, lastMessage: 'Great, thank you.', lastMessageAt: serverTimestamp(), lastSenderRole: 'customer', updatedAt: serverTimestamp(), adminUnreadCount: increment(1) });
  await assertSucceeds(answerBatch.commit());
  const staffReply = message(staff), staffBatch = writeBatch(staff);
  staffBatch.set(staffReply, { senderUid: 'staff-one', senderRole: 'admin', text: 'Happy to help.', product: null, createdAt: serverTimestamp() });
  staffBatch.update(ref(staff), { lastMessageId: staffReply.id, lastMessage: 'Happy to help.', lastMessageAt: serverTimestamp(), lastSenderRole: 'admin', updatedAt: serverTimestamp(), customerUnreadCount: increment(1) });
  await assertSucceeds(staffBatch.commit());
  await assertFails(setDoc(doc(admin, 'luxStaff', 'new-staff'), { displayName: 'New', email: 'new@example.com', role: 'staff', active: true, createdAt: serverTimestamp(), createdBy: 'admin-one' }));
  await assertSucceeds(setDoc(doc(owner, 'luxStaff', 'new-staff'), { displayName: 'New', email: 'new@example.com', role: 'staff', active: true, createdAt: serverTimestamp(), createdBy: 'owner-one' }));
  await assertSucceeds(updateDoc(doc(owner, 'luxStaff', 'new-staff'), { active: false }));
  await assertFails(updateDoc(doc(admin, 'luxStaff', 'new-staff'), { active: true }));
  await assertFails(updateDoc(doc(owner, 'luxStaff', 'owner-one'), { active: false }));
  await assertFails(setDoc(doc(staff, 'luxBlockedCustomers', 'guest-one'), { blockedAt: serverTimestamp(), blockedBy: 'staff-one' }));
  await assertSucceeds(setDoc(doc(admin, 'luxBlockedCustomers', 'guest-one'), { blockedAt: serverTimestamp(), blockedBy: 'admin-one' }));
  await assertFails(getDoc(ref(guest)));
  await assertFails(updateDoc(ref(guest), { customerDeliveredAt: serverTimestamp() }));
  await assertFails(deleteDoc(ref(admin)));
  await assertSucceeds(deleteDoc(doc(owner, 'luxConversations', 'guest-one', 'messages', first.id)));
  await assertSucceeds(deleteDoc(doc(owner, 'luxConversations', 'guest-one', 'messages', reply.id)));
  await assertSucceeds(deleteDoc(doc(owner, 'luxConversations', 'guest-one', 'messages', answer.id)));
  await assertSucceeds(deleteDoc(doc(owner, 'luxConversations', 'guest-one', 'messages', staffReply.id)));
  await assertSucceeds(deleteDoc(ref(owner)));
  await assertSucceeds(deleteDoc(doc(admin, 'luxBlockedCustomers', 'guest-one')));
  console.log('Lux chat rules: guest isolation, role and assignment access, staff management, block, delete, atomic send, anti-spam, receipts and unread counters passed.');
} finally { await env.cleanup(); }
